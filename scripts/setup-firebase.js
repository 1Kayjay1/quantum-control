#!/usr/bin/env node
const fs = require('fs')
const path = require('path')

function readStdin() {
  return new Promise((resolve, reject) => {
    let data = ''
    if (process.stdin.isTTY) return resolve(null)
    process.stdin.setEncoding('utf8')
    process.stdin.on('data', (chunk) => {
      data += chunk
    })
    process.stdin.on('end', () => resolve(data))
    process.stdin.on('error', reject)
  })
}

function extractConfig(input) {
  const start = input.indexOf('const firebaseConfig')
  if (start === -1) return null
  const braceIndex = input.indexOf('{', start)
  if (braceIndex === -1) return null

  let depth = 0
  for (let index = braceIndex; index < input.length; index += 1) {
    if (input[index] === '{') depth += 1
    else if (input[index] === '}') {
      depth -= 1
      if (depth === 0) {
        return input.slice(braceIndex, index + 1)
      }
    }
  }

  return null
}

async function main() {
  try {
    const argPath = process.argv[2]
    let input = null

    if (argPath) {
      input = fs.readFileSync(path.resolve(process.cwd(), argPath), 'utf8')
    } else {
      input = await readStdin()
      if (!input) {
        console.error(
          'Usage: node scripts/setup-firebase.js [path-to-file]\\nOr pipe the snippet into the script:',
        )
        console.error(
          "PowerShell example:\\n@'\\nPASTE CONTENT\\n'@ > paste.txt; node scripts/setup-firebase.js paste.txt",
        )
        process.exit(2)
      }
    }

    const configBody = extractConfig(input)
    if (!configBody) {
      console.error('Could not find `const firebaseConfig = { ... }` in the input.')
      process.exit(3)
    }

    const out = `// Auto-generated by scripts/setup-firebase.js
import { initializeApp } from "firebase/app"
import { getAnalytics, isSupported } from "firebase/analytics"

const firebaseConfig = ${configBody}

export const app = initializeApp(firebaseConfig)
export let analytics: ReturnType<typeof getAnalytics> | undefined

isSupported()
  .then((supported) => {
    if (supported) analytics = getAnalytics(app)
  })
  .catch(() => {})

export default firebaseConfig
`

    const outDir = path.resolve(process.cwd(), 'src')
    if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true })

    const outPath = path.join(outDir, 'firebase.ts')
    fs.writeFileSync(outPath, out, 'utf8')
    console.log(`Wrote ${outPath}`)

    const pidMatch = configBody.match(/projectId\s*:\s*['"]([^'"]+)['"]/)
    if (pidMatch?.[1]) {
      const firebaserc = { projects: { default: pidMatch[1] } }
      const rcPath = path.resolve(process.cwd(), '.firebaserc')
      fs.writeFileSync(rcPath, JSON.stringify(firebaserc, null, 2), 'utf8')
      console.log(`Updated .firebaserc with projectId: ${pidMatch[1]}`)
    } else {
      console.log('projectId not found in config; .firebaserc not updated.')
    }

    const firebaseJsonPath = path.resolve(process.cwd(), 'firebase.json')
    if (!fs.existsSync(firebaseJsonPath)) {
      const firebaseJson = {
        hosting: {
          public: 'dist',
          ignore: ['firebase.json', '**/.*', '**/node_modules/**'],
          rewrites: [{ source: '**', destination: '/index.html' }],
        },
      }
      fs.writeFileSync(firebaseJsonPath, JSON.stringify(firebaseJson, null, 2), 'utf8')
      console.log('Created firebase.json (serves dist and configures SPA rewrites)')
    } else {
      console.log('firebase.json already exists; leaving it unchanged.')
    }

    console.log('\nNext steps:')
    console.log('1) Install dependencies: npm install')
    console.log('2) Build the project: npm run build')
    console.log('3) Deploy: npm run deploy (or npx firebase deploy --only hosting)')
    process.exit(0)
  } catch (error) {
    console.error('Error:', error?.message || error)
    process.exit(1)
  }
}

main()
